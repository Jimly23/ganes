<?php

namespace App\Http\Controllers\Api;

use App\Http\Controllers\Controller;
use App\Models\Article;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\Storage;
use Illuminate\Support\Facades\Validator;

class ArticleController extends Controller
{
    public function index()
    {
        return response()->json([
            'status' => 'success',
            'data' => Article::query()->latest('tanggal_posting')->latest('id')->get(),
        ]);
    }

    public function store(Request $request)
    {
        $validator = Validator::make($request->all(), [
            'judul_artikel' => 'required|string|max:255',
            'deskripsi_singkat' => 'required|string',
            'tanggal_posting' => 'required|date',
            'gambar' => 'required|image|mimes:jpeg,png,jpg,gif,webp|max:5120',
            'isi_artikel' => 'required|string',
        ]);

        if ($validator->fails()) {
            return response()->json(['status' => 'error', 'errors' => $validator->errors()], 422);
        }

        $data = $request->except('gambar');
        $data['isi_artikel'] = $this->sanitizeArticleContent($data['isi_artikel']);
        $article = Article::create($data);
        if ($request->hasFile('gambar')) {
            $article->update(['gambar' => $request->file('gambar')->store('articles', 'public')]);
        }

        return response()->json([
            'status' => 'success',
            'message' => 'Artikel berhasil dibuat',
            'data' => $article->fresh(),
        ], 201);
    }

    public function show(string $id)
    {
        $article = Article::find($id);
        if (!$article) {
            return response()->json(['status' => 'error', 'message' => 'Artikel tidak ditemukan'], 404);
        }

        return response()->json(['status' => 'success', 'data' => $article]);
    }

    public function update(Request $request, string $id)
    {
        $article = Article::find($id);
        if (!$article) {
            return response()->json(['status' => 'error', 'message' => 'Artikel tidak ditemukan'], 404);
        }

        $validator = Validator::make($request->all(), [
            'judul_artikel' => 'sometimes|required|string|max:255',
            'deskripsi_singkat' => 'sometimes|required|string',
            'tanggal_posting' => 'sometimes|required|date',
            'gambar' => 'nullable|image|mimes:jpeg,png,jpg,gif,webp|max:5120',
            'isi_artikel' => 'sometimes|required|string',
        ]);

        if ($validator->fails()) {
            return response()->json(['status' => 'error', 'errors' => $validator->errors()], 422);
        }

        $data = $request->except('gambar');
        if (array_key_exists('isi_artikel', $data)) {
            $data['isi_artikel'] = $this->sanitizeArticleContent($data['isi_artikel']);
        }
        $article->update($data);
        if ($request->hasFile('gambar')) {
            if ($article->gambar) {
                Storage::disk('public')->delete($article->gambar);
            }
            $article->update(['gambar' => $request->file('gambar')->store('articles', 'public')]);
        }

        return response()->json([
            'status' => 'success',
            'message' => 'Artikel berhasil diperbarui',
            'data' => $article->fresh(),
        ]);
    }

    public function destroy(string $id)
    {
        $article = Article::find($id);
        if (!$article) {
            return response()->json(['status' => 'error', 'message' => 'Artikel tidak ditemukan'], 404);
        }

        if ($article->gambar) {
            Storage::disk('public')->delete($article->gambar);
        }
        $article->delete();

        return response()->json(['status' => 'success', 'message' => 'Artikel berhasil dihapus']);
    }

    /**
     * Keep the existing plain-text format valid while allowing the safe HTML
     * generated by the admin Tiptap editor.
     */
    private function sanitizeArticleContent(string $content): string
    {
        if (!preg_match('/<[a-z][\s\S]*>/i', $content)) {
            return $content;
        }

        $allowedTags = '<p><h1><h2><h3><h4><h5><h6><strong><b><em><i><u><s><ul><ol><li><blockquote><code><pre><hr><br><a>';
        $content = strip_tags($content, $allowedTags);
        $content = preg_replace('/\s+on[a-z]+\s*=\s*(?:"[^"]*"|\'[^\']*\'|[^\s>]+)/i', '', $content) ?? $content;
        $content = preg_replace_callback('/\sstyle=("|\')(.*?)\1/i', static function ($match) {
            preg_match('/text-align\s*:\s*(left|center|right|justify)/i', $match[2], $alignment);
            return isset($alignment[1]) ? ' style="text-align: ' . strtolower($alignment[1]) . '"' : '';
        }, $content) ?? $content;
        $content = preg_replace_callback('/<a\b[^>]*>/i', static function ($match) {
            preg_match("/href\\s*=\\s*['\"]?([^'\"\\s>]+)['\"]?/i", $match[0], $hrefMatch);
            $href = $hrefMatch[1] ?? '';
            if ($href === '' || preg_match('/^(?:javascript|data|vbscript):/i', trim(html_entity_decode($href)))) {
                return '<a>';
            }
            return '<a href="' . e($href) . '" target="_blank" rel="noopener noreferrer">';
        }, $content) ?? $content;

        return $content;
    }
}
